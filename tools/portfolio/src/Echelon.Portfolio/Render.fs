/// Deterministic Markdown views generated from the JSON records, so facts are maintained once.
module Echelon.Portfolio.Render

open System
open System.Text.Json.Nodes
open Echelon.Portfolio.Json

let private cell (s: string) =
    s.Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ").Trim()

let private joined name o =
    strings name o |> String.concat ", " |> cell

let private text name o =
    tryString name o |> Option.defaultValue "" |> cell

let private header (title: string) (source: string) =
    [ $"# {title}"
      ""
      $"<!-- Generated by tools/portfolio from {source}. Do not edit by hand: run"
      "     `dotnet run --project tools/portfolio/src/Echelon.Portfolio.Cli -- render --root .` -->"
      "" ]

let repositoriesMarkdown (doc: JsonObject) : string =
    let rows =
        objects "repositories" doc
        |> List.sortBy (fun r -> (text "echelonRelation" r, text "id" r))
        |> List.map (fun r ->
            let prov = if tryBool "provisional" r = Some true then " (provisional)" else ""

            $"""| `{text "id" r}` | [{text "displayName" r}](https://github.com/{text "repository" r}) | {text "visibility" r} | {text "echelonRelation" r} | {text "purpose" r}{prov} | {joined "systems" r} | {joined "initiatives" r} | {text "developmentStatus" r} | {text "maturity" r} | {text "latestRelease" r} | {text "lastVerified" r} |""")

    let aggregate =
        match tryObject "privateRepositories" doc with
        | Some p ->
            let count = tryInt "count" p |> Option.map string |> Option.defaultValue "unknown"
            [ ""; $"""Private repositories not named here: **{count}** ({text "basis" p}).""" ]
        | None -> []

    (header "Echelon repository inventory (public projection)" "portfolio/repositories.json"
     @ [ "| Id | Repository | Visibility | Relation | Purpose | Systems | Initiatives | Status | Maturity | Latest release | Last verified |"
         "|---|---|---|---|---|---|---|---|---|---|---|" ]
     @ rows
     @ aggregate)
    |> String.concat "\n"
    |> fun s -> s + "\n"

let initiativesMarkdown (doc: JsonObject) : string =
    let rows =
        objects "initiatives" doc
        |> List.map (fun i ->
            if tryBool "withheld" i = Some true then
                $"""| {text "id" i} | *withheld* ({text "justificationCategory" i}, review by {text "reviewBy" i}) | | | | |"""
            else
                let prov = if tryBool "provisional" i = Some true then " (provisional)" else ""

                $"""| {text "id" i} | **{text "name" i}**{prov} — {text "description" i} | {text "status" i} | {joined "repositories" i} | {strings "nextActions" i |> List.tryHead |> Option.defaultValue "" |> cell} | {text "lastReview" i} |""")

    (header "Echelon strategic initiatives (public projection)" "portfolio/initiatives.json"
     @ [ $"""Source record: `{text "sourceRecord" doc}` (`{text "sourceDigest" doc}`)."""
         ""
         "| Id | Initiative | Status | Repositories | Next action | Last review |"
         "|---|---|---|---|---|---|" ]
     @ rows)
    |> String.concat "\n"
    |> fun s -> s + "\n"
